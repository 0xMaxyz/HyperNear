//! Hyperliquid L1 action signing ("phantom agent"), for `cancel` only.
//! connectionId = keccak256(msgpack(action) || nonce as u64 big-endian || 0x00 (no vault));
//! digest = EIP-712 `Agent(string source,bytes32 connectionId)` under domain Exchange / "1" / 1337 / 0x0,
//! source "a" on mainnet, "b" on testnet. Same scheme as hyperliquid-python-sdk `sign_l1_action`.
//! The msgpack is hand-encoded for the one fixed shape `{"type":"cancel","cancels":[{"a":u32,"o":u64}, …]}`
//! (key order as HL's SDKs send it), integers in msgpack's smallest form, as the SDKs' encoders produce.

use crate::eip712::{hash_struct, typed_digest, word_str, word_u64};
use near_sdk::env::{self, keccak256_array};
use near_sdk::near;

/// Most cancels one call signs (one MPC signature covers them all; this bounds the msgpack and HL request size).
pub const MAX_CANCELS: usize = 16;

const DOMAIN_TYPE: &[u8] =
    b"EIP712Domain(string name,string version,uint256 chainId,address verifyingContract)";
const AGENT_TYPE: &[u8] = b"Agent(string source,bytes32 connectionId)";

/// One order to cancel, in HL's own shape: `a` = asset index, `o` = order id.
#[near(serializers = [json])]
#[derive(Clone, Debug, PartialEq)]
pub struct HlCancel {
    pub a: u32,
    pub o: u64,
}

pub fn check_cancels(cancels: &[HlCancel]) {
    if cancels.is_empty() || cancels.len() > MAX_CANCELS {
        env::panic_str(&format!("cancels: 1 to {MAX_CANCELS} per call"));
    }
}

fn mp_uint(out: &mut Vec<u8>, v: u64) {
    if v < 0x80 {
        out.push(v as u8);
    } else if v <= 0xff {
        out.extend_from_slice(&[0xcc, v as u8]);
    } else if v <= 0xffff {
        out.push(0xcd);
        out.extend_from_slice(&(v as u16).to_be_bytes());
    } else if v <= 0xffff_ffff {
        out.push(0xce);
        out.extend_from_slice(&(v as u32).to_be_bytes());
    } else {
        out.push(0xcf);
        out.extend_from_slice(&v.to_be_bytes());
    }
}

/// fixstr only: every key and value here is shorter than 32 bytes.
fn mp_str(out: &mut Vec<u8>, s: &str) {
    out.push(0xa0 | s.len() as u8);
    out.extend_from_slice(s.as_bytes());
}

pub fn msgpack_cancel(cancels: &[HlCancel]) -> Vec<u8> {
    let mut m = Vec::with_capacity(24 + cancels.len() * 16);
    m.push(0x82); // map of 2
    mp_str(&mut m, "type");
    mp_str(&mut m, "cancel");
    mp_str(&mut m, "cancels");
    if cancels.len() < 16 {
        m.push(0x90 | cancels.len() as u8); // fixarray
    } else {
        m.push(0xdc); // array16
        m.extend_from_slice(&(cancels.len() as u16).to_be_bytes());
    }
    for c in cancels {
        m.push(0x82);
        mp_str(&mut m, "a");
        mp_uint(&mut m, c.a as u64);
        mp_str(&mut m, "o");
        mp_uint(&mut m, c.o);
    }
    m
}

pub fn connection_id(cancels: &[HlCancel], nonce: u64) -> [u8; 32] {
    let mut buf = msgpack_cancel(cancels);
    buf.extend_from_slice(&nonce.to_be_bytes());
    buf.push(0x00); // no vault address
    keccak256_array(&buf)
}

pub fn exchange_domain_separator() -> [u8; 32] {
    hash_struct(DOMAIN_TYPE, &[word_str("Exchange"), word_str("1"), word_u64(1337), [0u8; 32]])
}

/// The 32 bytes the leg's master key signs for this cancel.
pub fn cancel_digest(cancels: &[HlCancel], nonce: u64, mainnet: bool) -> [u8; 32] {
    let source = if mainnet { "a" } else { "b" };
    typed_digest(exchange_domain_separator(), hash_struct(AGENT_TYPE, &[word_str(source), connection_id(cancels, nonce)]))
}

#[cfg(test)]
mod tests {
    use super::*;
    use near_sdk::serde_json::{self, Value};

    // Generated by scripts/gen-l1-vectors.ts: packages/core hashHlL1Action (the HL SDK's msgpack) + viem hashTypedData.
    const VECTORS: &str = include_str!("../tests/vectors/l1_cancel.json");

    fn h32(s: &str) -> [u8; 32] {
        hex::decode(s.trim_start_matches("0x")).unwrap().try_into().unwrap()
    }
    fn case(c: &Value) -> (Vec<HlCancel>, u64, bool) {
        (
            serde_json::from_value(c["action"]["cancels"].clone()).unwrap(),
            c["nonce"].as_u64().unwrap(),
            c["mainnet"].as_bool().unwrap(),
        )
    }

    #[test]
    fn cancel_digests_match_the_sdk_vectors() {
        let v: Value = serde_json::from_str(VECTORS).unwrap();
        let cases = v["cases"].as_array().unwrap();
        assert!(cases.len() >= 10);
        for c in cases {
            assert_eq!(c["action"]["type"], "cancel");
            let (cancels, nonce, mainnet) = case(c);
            assert_eq!(connection_id(&cancels, nonce), h32(c["connectionId"].as_str().unwrap()), "connectionId {c}");
            assert_eq!(cancel_digest(&cancels, nonce, mainnet), h32(c["digest"].as_str().unwrap()), "digest {c}");
        }
    }

    #[test]
    fn digest_hl_testnet_accepted_in_c20() {
        let v: Value = serde_json::from_str(VECTORS).unwrap();
        let (cancels, nonce, mainnet) = case(&v["hlAccepted"]);
        assert_eq!(cancel_digest(&cancels, nonce, mainnet), h32(v["hlAccepted"]["digest"].as_str().unwrap()));
    }

    #[test]
    fn source_byte_separates_mainnet_and_testnet() {
        let c = [HlCancel { a: 3, o: 64_820_881_296 }];
        // same connectionId, different digest: a testnet signature is useless on mainnet and back
        assert_ne!(cancel_digest(&c, 1, true), cancel_digest(&c, 1, false));
        let v: Value = serde_json::from_str(VECTORS).unwrap();
        let (a, b) = (&v["cases"][1], &v["cases"][0]); // same action and nonce: mainnet, testnet
        assert_eq!((a["mainnet"].as_bool(), b["mainnet"].as_bool()), (Some(true), Some(false)));
        assert_eq!(a["connectionId"], b["connectionId"]);
        assert_eq!(cancel_digest(&case(a).0, case(a).1, true), h32(a["digest"].as_str().unwrap()));
        assert_eq!(cancel_digest(&case(b).0, case(b).1, false), h32(b["digest"].as_str().unwrap()));
    }

    #[test]
    fn msgpack_shape() {
        let m = msgpack_cancel(&[HlCancel { a: 3, o: 300 }]);
        assert_eq!(hex::encode(m), "82a474797065a663616e63656ca763616e63656c739182a16103a16fcd012c");
    }

    #[test]
    #[should_panic(expected = "cancels: 1 to 16 per call")]
    fn cap_rejects_17() {
        check_cancels(&vec![HlCancel { a: 0, o: 1 }; MAX_CANCELS + 1]);
    }

    #[test]
    #[should_panic(expected = "cancels: 1 to 16 per call")]
    fn cap_rejects_empty() {
        check_cancels(&[]);
    }
}
