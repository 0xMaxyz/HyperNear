describe('[Epic 1.2.9] Re-home withdraw/sendAsset/setReferrer/approveAgent/approveBuilderFee/updateLeverage', () => {
  describe.each(CASES)('$actionType', ({ fixtureName, tier, call }) => {
    it('the wrapper exposes the endpoint and returns the transport response', async () => {
      const { client } = createWrapper();
      const result = await call(client);
      expect(result).toEqual({ status: 'ok', response: { type: 'default' } });
    });

    it(`signs via the ${tier} tier's async signer only`, async () => {
      const { client, agent, master } = createWrapper();
      await call(client);

      const signed = tier === 'agent' ? agent : master;
      const other = tier === 'agent' ? master : agent;
      expect(signed.payloads).toHaveLength(1);
      expect(other.payloads).toHaveLength(0);
    });

    it('the request signing matches the golden fixture byte-for-byte', async () => {
      const fixture = loadGoldenFixture(fixtureName);
      const { client, requests } = createWrapper();
      await call(client);

      expect(requests).toHaveLength(1);
      expect(requests[0].endpoint).toBe('exchange');

      const payload = requests[0].payload;
      expect(lowercaseHexAddresses(payload.action)).toEqual(lowercaseHexAddresses(fixture.input.action));
      expect(payload.nonce).toBe(WRAPPER_NONCE);
      // Deterministic ECDSA (RFC 6979): equal signatures <=> equal preimage.
      expect(payload.signature).toEqual(fixture.output.signature);
    });

    it(`fails without a configured ${tier} signer, naming the missing tier`, async () => {
      const override = tier === 'agent' ? { agentSigner: undefined } : { masterSigner: undefined };
      const { client } = createWrapper(override);
      await expect(call(client)).rejects.toThrow(new RegExp(`${tier} signer`, 'i'));
    });

    it('testnet integration: replays the recorded cassette response and parses it', async () => {
      const { client } = createWrapper();
      const result = await call(client);

      expect(result.status).toBe('ok');
      expect(result.response.type).toBe('default');
    });
  });

  describe('signing-scheme grouping (documents the acceptance-criteria correction above)', () => {
    it('withdraw, sendAsset, approveAgent, approveBuilderFee are user-signed (master tier)', () => {
      const userSigned = CASES.filter((c) => c.tier === 'master').map((c) => c.actionType);
      expect(userSigned.sort()).toEqual(
        ['approveAgent', 'approveBuilderFee', 'sendAsset', 'withdraw3'].sort()
      );
    });

    it('setReferrer and updateLeverage are L1 actions (agent tier), not user-signed', () => {
      const l1Signed = CASES.filter((c) => c.tier === 'agent').map((c) => c.actionType);
      expect(l1Signed.sort()).toEqual(['setReferrer', 'updateLeverage'].sort());
    });

    it("each fixture's recorded signingScheme matches the tier it dispatches to", () => {
      for (const { fixtureName, tier } of CASES) {
        const fixture = loadGoldenFixture(fixtureName);
        const expectedScheme = tier === 'master' ? 'sign_user_signed_action' : 'sign_l1_action';
        expect(fixture.signingScheme, fixtureName).toBe(expectedScheme);
      }
    });
  });
});

