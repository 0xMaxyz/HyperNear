describe('[Epic 1.2.8] closeAllPositions through the wrapper', () => {
  const USER_ADDRESS = '0x0000000000000000000000000000000000000001';

  const ASSETS: Record<string, HlCloseAllPositionsAssetInfo> = {
    BTC: { asset: 0, szDecimals: 5, midPx: '50000' },
    ETH: { asset: 1, szDecimals: 4, midPx: '3000' },
    SOL: { asset: 2, szDecimals: 2, midPx: '150' },
  };

  function stubReadTransport(assetPositions: unknown[]): { transport: HlTransport; requests: unknown[] } {
    const requests: unknown[] = [];
    const transport: HlTransport = {
      async request(endpoint, payload) {
        requests.push({ endpoint, payload });
        if (endpoint === 'info') {
          return {
            marginSummary: {},
            crossMarginSummary: {},
            crossMaintenanceMarginUsed: '0',
            withdrawable: '0',
            assetPositions,
            time: 1700000000000,
          };
        }
        return { status: 'ok', response: { type: 'order', data: { statuses: [{ resting: { oid: 1 } }] } } };
      },
    };
    return { transport, requests };
  }

  function position(coin: string, szi: string) {
    return { type: 'oneWay', position: { coin, szi } };
  }

  it('reads clearinghouseState and closes every non-zero position via one batched reduce-only order', async () => {
    const { transport, requests } = stubReadTransport([
      position('BTC', '0.5'),
      position('ETH', '-1.2'),
      position('SOL', '0.0'),
    ]);
    const agent = createSpySigner(baseSigner());
    const client = new HlClient({ network: 'testnet', transport, agentSigner: agent.signer });

    const result = await client.closeAllPositions({ user: USER_ADDRESS, assets: ASSETS });

    expect(result.closedCoins).toEqual(['BTC', 'ETH']);
    expect(result.order?.status).toBe('ok');
    expect(requests).toHaveLength(2);
    expect((requests[0] as { endpoint: string }).endpoint).toBe('info');
    expect((requests[0] as { payload: { type: string; user: string } }).payload).toEqual({
      type: 'clearinghouseState',
      user: USER_ADDRESS,
    });

    const exchangePayload = (requests[1] as { endpoint: string; payload: Record<string, unknown> }).payload;
    expect((requests[1] as { endpoint: string }).endpoint).toBe('exchange');
    const action = exchangePayload.action as { type: string; orders: HlOrderInput[]; grouping: string };
    expect(action.type).toBe('order');
    expect(action.grouping).toBe('na');
    expect(action.orders).toHaveLength(2);

    // Closing a long (szi > 0) sells; closing a short (szi < 0) buys. Every
    // close order is reduce-only.
    expect(action.orders[0]).toMatchObject({ a: 0, b: false, s: '0.5', r: true });
    expect(action.orders[1]).toMatchObject({ a: 1, b: true, s: '1.2', r: true });
    expect(action.orders[0].t).toEqual({ limit: { tif: 'FrontendMarket' } });
  });

  it('computes the slippage-adjusted crossing price the same way placeMarketOrder does', async () => {
    const { transport, requests } = stubReadTransport([position('BTC', '0.5')]);
    const client = new HlClient({ network: 'testnet', transport, agentSigner: baseSigner() });

    await client.closeAllPositions({ user: USER_ADDRESS, assets: ASSETS });

    const exchangePayload = (requests[1] as { payload: { action: { orders: HlOrderInput[] } } }).payload;
    const sellPrice = exchangePayload.action.orders[0].p;
    expect(sellPrice).toBe(computeSlippagePrice('50000', 0.08, false, 5));
  });

  it('honors a custom slippage', async () => {
    const { transport, requests } = stubReadTransport([position('BTC', '0.5')]);
    const client = new HlClient({ network: 'testnet', transport, agentSigner: baseSigner() });

    await client.closeAllPositions({ user: USER_ADDRESS, assets: ASSETS, slippage: 0.02 });

    const exchangePayload = (requests[1] as { payload: { action: { orders: HlOrderInput[] } } }).payload;
    expect(exchangePayload.action.orders[0].p).toBe(computeSlippagePrice('50000', 0.02, false, 5));
  });

  it('attaches an optional builder fee to the batched order action', async () => {
    const { transport, requests } = stubReadTransport([position('BTC', '0.5')]);
    const client = new HlClient({ network: 'testnet', transport, agentSigner: baseSigner() });

    await client.closeAllPositions({
      user: USER_ADDRESS,
      assets: ASSETS,
      builder: { address: '0x0000000000000000000000000000000000000002', fee: 20 },
    });

    const exchangePayload = (requests[1] as { payload: { action: { builder?: { b: string; f: number } } } })
      .payload;
    expect(exchangePayload.action.builder).toEqual({
      b: '0x0000000000000000000000000000000000000002',
      f: 20,
    });
  });

  it("signs via the agent tier's async signer only, like `order`", async () => {
    const { transport } = stubReadTransport([position('BTC', '0.5')]);
    const agent = createSpySigner(baseSigner());
    const master = createSpySigner(baseSigner());
    const client = new HlClient({
      network: 'testnet',
      transport,
      agentSigner: agent.signer,
      masterSigner: master.signer,
    });

    await client.closeAllPositions({ user: USER_ADDRESS, assets: ASSETS });

    expect(agent.payloads).toHaveLength(1);
    expect(master.payloads).toHaveLength(0);
  });

  it('throws naming the coin when an open position has no matching asset info', async () => {
    const { transport } = stubReadTransport([position('DOGE', '100')]);
    const client = new HlClient({ network: 'testnet', transport, agentSigner: baseSigner() });

    await expect(
      client.closeAllPositions({ user: USER_ADDRESS, assets: ASSETS })
    ).rejects.toThrow(/DOGE/);
  });

  describe('empty-position case is a no-op', () => {
    it('sends no exchange request and returns no closed coins when every position is zero', async () => {
      const { transport, requests } = stubReadTransport([position('SOL', '0.0'), position('BTC', '0')]);
      const client = new HlClient({ network: 'testnet', transport });

      const result = await client.closeAllPositions({ user: USER_ADDRESS, assets: ASSETS });

      expect(result).toEqual({ closedCoins: [] });
      expect(requests).toHaveLength(1);
      expect((requests[0] as { endpoint: string }).endpoint).toBe('info');
    });

    it('sends no exchange request when the account has no positions at all', async () => {
      const { transport, requests } = stubReadTransport([]);
      const client = new HlClient({ network: 'testnet', transport });

      const result = await client.closeAllPositions({ user: USER_ADDRESS, assets: ASSETS });

      expect(result).toEqual({ closedCoins: [] });
      expect(requests).toHaveLength(1);
    });

    it('does not require an agent signer when there is nothing to close', async () => {
      const { transport } = stubReadTransport([position('BTC', '0')]);
      const client = new HlClient({ network: 'testnet', transport });

      await expect(
        client.closeAllPositions({ user: USER_ADDRESS, assets: ASSETS })
      ).resolves.toEqual({ closedCoins: [] });
    });
  });

  it('testnet integration: replays the recorded cassette clearinghouseState + order responses', async () => {
    const { client, requests } = createWrapper();

    const result = await client.closeAllPositions({
      user: USER_ADDRESS,
      assets: ASSETS,
    });

    expect(result.closedCoins).toEqual(['BTC', 'ETH']);
    expect(result.order?.status).toBe('ok');
    expect(requests).toHaveLength(2);
    expect(requests[0].endpoint).toBe('info');
    expect(requests[1].endpoint).toBe('exchange');
  });
});

