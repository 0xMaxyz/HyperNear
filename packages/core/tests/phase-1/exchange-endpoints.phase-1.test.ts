// applies unchanged to the two new action types rather than re-deriving it.
describe('[Epic 1.2.3] nonce ordering on modify/batchModify', () => {
  function recordingNonceTransport(): { transport: HlTransport; nonces: number[] } {
    const nonces: number[] = [];
    const transport: HlTransport = {
      async request(_endpoint, payload) {
        const wire = JSON.parse(JSON.stringify(payload)) as Record<string, unknown>;
        nonces.push(wire.nonce as number);
        const action = wire.action as Record<string, unknown>;
        if (action.type === 'batchModify') {
          return { status: 'ok', response: { type: 'order', data: { statuses: [{ resting: { oid: 1 } }] } } };
        }
        return { status: 'ok', response: { type: 'default' } };
      },
    };
    return { transport, nonces };
  }

  it('the default nonce manager issues strictly increasing, unique nonces across concurrent modifyOrder calls', async () => {
    const { transport, nonces } = recordingNonceTransport();
    const client = new HlClient({ network: 'testnet', transport, agentSigner: baseSigner() });
    const count = 12;
    await Promise.all(
      Array.from({ length: count }, (_, i) => client.modifyOrder({ oid: i, order: MODIFY_ORDER_INPUT }))
    );

    expect(nonces).toHaveLength(count);
    expect(new Set(nonces).size).toBe(count);
    for (let i = 1; i < nonces.length; i += 1) {
      expect(nonces[i], `nonce[${i}] must exceed nonce[${i - 1}]`).toBeGreaterThan(nonces[i - 1]);
    }
  });

  it('the default nonce manager orders batchModifyOrder alongside modifyOrder on the same address, strictly increasing', async () => {
    const { transport, nonces } = recordingNonceTransport();
    const client = new HlClient({ network: 'testnet', transport, agentSigner: baseSigner() });

    await Promise.all([
      client.modifyOrder({ oid: 1, order: MODIFY_ORDER_INPUT }),
      client.batchModifyOrder({ modifies: [{ oid: 2, order: MODIFY_ORDER_INPUT }] }),
      client.modifyOrder({ oid: 3, order: MODIFY_ORDER_INPUT }),
    ]);

    expect(nonces).toHaveLength(3);
    expect(new Set(nonces).size).toBe(3);
  });

  it('an injected nonceSource is forwarded verbatim to modifyOrder/batchModifyOrder, same as order', async () => {
    let counter = 1_700_000_000_000;
    const { transport, nonces } = recordingNonceTransport();
    const client = new HlClient({
      network: 'testnet',
      transport,
      agentSigner: baseSigner(),
      nonceSource: () => (counter += 1),
    });

    await client.modifyOrder({ oid: 1, order: MODIFY_ORDER_INPUT });
    await client.batchModifyOrder({ modifies: [{ oid: 2, order: MODIFY_ORDER_INPUT }] });

    expect(nonces).toEqual([1_700_000_000_001, 1_700_000_000_002]);
  });
});

