// @nktkas/hyperliquid canonicalizes `address`-typed action fields to
// lowercase on the wire (see its `canonicalize`/`Address` valibot schema);
// the Python-generated golden fixtures keep eth_account's EIP-55 checksum
// casing. Case doesn't change the EIP-712 "address" encoding or therefore
// the signature — only the JSON string's cosmetic casing — so fixture diffs
// compare with both sides lowercased instead of asserting exact fixture
// casing survives the wrapper.
function lowercaseHexAddresses<T>(value: T): T {
  if (typeof value === 'string') {
    return (/^0x[0-9a-fA-F]{40}$/.test(value) ? value.toLowerCase() : value) as unknown as T;
  }
  if (Array.isArray(value)) {
    return value.map(lowercaseHexAddresses) as unknown as T;
  }
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value as Record<string, unknown>).map(([k, v]) => [k, lowercaseHexAddresses(v)])
    ) as T;
  }
  return value;
}

function createSpySigner(base: HlAsyncSigner) {
  const payloads: HlSignPayload[] = [];
  const signer: HlAsyncSigner = {
    address: base.address,
    sign: async (payload) => {
      payloads.push(payload);
      await new Promise((resolve) => setTimeout(resolve, 0));
      return base.sign(payload);
    },
  };
  return { signer, payloads };
}

// Every fixture in this suite is signed by the same throwaway wallet
// (generate_fixtures.py's TEST_PRIVATE_KEY) — reuse one base signer and wrap
// it independently per tier so agent/master call counts can be asserted
// separately.
function baseSigner(): HlAsyncSigner {
  return testOnlyRawKeySigner(loadGoldenFixture('withdraw3').wallet.privateKey as `0x${string}`);
}

function createWrapper(overrides: Partial<HlClientConfig> = {}) {
  const { transport, requests } = createCassetteTransport('exchange-endpoints');
  const agent = createSpySigner(baseSigner());
  const master = createSpySigner(baseSigner());
  const client = new HlClient({
    network: 'testnet',
    transport,
    agentSigner: agent.signer,
    masterSigner: master.signer,
    nonceSource: () => WRAPPER_NONCE,
    ...overrides,
  });
  return { client, requests, agent, master };
}

